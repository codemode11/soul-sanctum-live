export function getSaintForDate(month: number, day: number): DailySaintEntry {
  const match = SAINTS_DATABASE.find(s => s.month === month && s.day === day);
  if (match) return match;

  // Deterministic daily resolution from Butler's Lives of the Saints for any other day of the year
  const monthName = MONTH_NAMES[(month - 1 + 12) % 12] || 'October';
  const dayIndex = (month * 31 + day) % DAILY_BUTLER_ROTATION.length;
  const template = DAILY_BUTLER_ROTATION[dayIndex];

  return {
    id: `butler-${month}-${day}`,
    name: template.name,
    title: template.title,
    feastDate: `${monthName} ${day}`,
    month,
    day,
    birthYear: template.birthYear,
    deathYear: template.deathYear,
    patronage: template.patronage,
    symbols: template.symbols,
    liturgicalColor: template.liturgicalColor,
    wikiSlug: template.wikiSlug,
    butlerReference: `Butler's Lives of the Saints — ${monthName} ${day}`,
    imageUrl: template.imageUrl,
    biography: template.biography,
    quote: template.quote,
    prayer: template.prayer,
    canonization: template.canonization,
    companionSaints: template.companionSaints
  };
}
