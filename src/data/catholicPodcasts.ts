/**
 * Returns all podcasts flattened or filtered by category.
 */
export function getPodcastsByCategory(category: CatholicPodcastCategory): CatholicPodcastShow[] {
  if (category === 'all') return CATHOLIC_PODCASTS_DATABASE;
  return CATHOLIC_PODCASTS_DATABASE.filter(show => show.category === category);
}

/**
 * Returns all episodes across all shows, ordered by release or priority.
 */
export function getAllPodcastEpisodes(): PodcastEpisode[] {
  return CATHOLIC_PODCASTS_DATABASE.flatMap(show => show.episodes);
}

/**
 * Returns the featured "Podcast Episode of the Day" with liturgical resonance.
 */
export function getFeaturedPodcastEpisode(): PodcastEpisode {
  return CATHOLIC_PODCASTS_DATABASE[0].episodes[0];
}
